export function iconSvg(name, label = '') {
  if (!(name in icons)) throw new Error(`Unknown Taiwan.md icon: ${name}`);
  const safeLabel = label.replace(
    /[&<>"']/g,
    (c) =>
      ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[
        c
      ],
  );
  return `<svg class="twmd-icon" viewBox="0 0 24 24" width="1em" height="1em" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="butt" stroke-linejoin="miter" focusable="false" ${label ? `role="img" aria-label="${safeLabel}"` : 'aria-hidden="true"'}><use href="/icons/taiwan.svg#${name}"/></svg>`;
}
